"""Generate the mod's keyboard UI library from the game's own XAML.

Three templates are produced:

  * VSWS_VisibilityButtonTemplate - the game's visibility button, reading its
    state from a text block the mod writes to, with the mod's labels;
  * VSWS_WeaponEQTemplate - a weapon slot plus that button, modelled on the
    helmet's wrapper; it tells the mod which character and slot it shows;
  * CharacterEquipmentTemplate - the game's template with the four weapon
    slots using VSWS_WeaponEQTemplate. Nothing else in it is changed.

Regenerate after a game update:

    python scripts/gen_ui.py

Needs the vanilla XAML extracted to vanilla/ (see docs/recon.md).
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
VANILLA = ROOT / "vanilla/Game/Public/Game/GUI/Library/CharacterSheetTemplates_k.xaml"
OUT = ROOT / "mod/Mods/Gwynerva_VisibleShieldsAndWeaponSets/GUI/Library/Lib_Keyboard.xaml"

SLOTS = ["EquipmentMeleeMainSlot", "EquipmentMeleeOffSlot", "EquipmentRangedMainSlot", "EquipmentRangedOffSlot"]

# The mod's labels (Localization/*/Gwynerva_VisibleShieldsAndWeaponSets.xml) in place of the helmet's.
LABELS = {
    "h90154bd4g08b9g46efg8e70gbce5d5a99e1a": "h153c3f7cga3aeg4d25gb8dcg439be99a27e1",  # visible
    "h57dce093g8d4ag43b4gb7a3g525250a499c1": "h4015e57fg601ag44eagac2fga543834139c8",  # hidden in dialogues
    "h5bd7b04cg842eg4892ga9b7ga421ad707517": "hb8aca5ffg5327g491eg9cd9gcfcde0e667bd",  # hidden
}

# The fourth state, which the game does not have: its label, and the pictures
# that mark it (the controller UI's icons for the melee and the ranged set).
ACTIVE_SET_LABEL = "h02045512g42b3g4e65gbb80g2860f50b9145"
SET_MARK_MELEE = "pack://application:,,,/Core;component/Assets/CharacterPanel_c/c_ico_equipment_meleeSet_h.png"
SET_MARK_RANGED = "pack://application:,,,/Core;component/Assets/CharacterPanel_c/c_ico_equipment_rangedSet_h.png"

HEADER = """<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
                    xmlns:d="http://schemas.microsoft.com/expression/blend/2008"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"
                    xmlns:b="http://schemas.microsoft.com/xaml/behaviors"
                    xmlns:mc="http://schemas.openxmlformats.org/markup-compatibility/2006"
                    xmlns:ls="clr-namespace:ls;assembly=Code"
                    xmlns:noesis="clr-namespace:NoesisGUIExtensions;assembly=Noesis.GUI.Extensions"
                    xmlns:System="clr-namespace:System;assembly=mscorlib"
                    mc:Ignorable="d">

    <!-- Generated by scripts/gen_ui.py from the game's CharacterSheetTemplates_k.xaml. -->
"""

# How the template talks to the mod's Lua. Script cannot read bound values off
# an element, so the XAML passes the data itself, as three commands in a row:
# the character, the slot, then the hidden text block whose Text is the state
# (the button's triggers read it by element name, as the game's own templates
# do with other elements). The mod writes the mode name into that text block.
#
# The commands are not on any panel: the mod puts one object holding them in
# the Tag of ContentRoot, the container of every widget, which the game's own
# pages also reach by name.
COMMANDS = "ElementName=ContentRoot"


def actions(last):
    def call(command, parameter):
        return (f'<b:InvokeCommandAction Command="{{Binding Tag.{command}, {COMMANDS}}}" '
                f'CommandParameter="{parameter}"/>')
    pad = "\n                    "
    return pad.join([
        call("VSWS_CharacterCommand", "{Binding DataContext, ElementName=EquipmentSlots}"),
        call("VSWS_SlotCommand", "{Binding DataContext, ElementName=VSWS_Root}"),
        call(last, "{Binding ElementName=VSWS_State}"),
    ])


WEAPON_EQ_TEMPLATE = f"""    <ControlTemplate x:Key="VSWS_WeaponEQTemplate" TargetType="Control">
        <Grid x:Name="VSWS_Root" HorizontalAlignment="Left">
            <b:Interaction.Triggers>
                <b:EventTrigger EventName="Loaded">
                    {actions("VSWS_ShowCommand")}
                </b:EventTrigger>
                <b:EventTrigger EventName="MouseEnter">
                    {actions("VSWS_ShowCommand")}
                </b:EventTrigger>
            </b:Interaction.Triggers>
            <TextBlock x:Name="VSWS_State" Text="Visible" Visibility="Collapsed"/>
            <ls:LSButton x:Name="EquipmentWeaponSlot" Style="{{StaticResource EquipmentSlotStyle}}" Tag="{{TemplateBinding Tag}}"/>
            <ls:LSButton x:Name="VisibilityButton" VerticalAlignment="Top" HorizontalAlignment="Left" Margin="-4,-40,0,0" Template="{{StaticResource VSWS_VisibilityButtonTemplate}}" Opacity="0">
                <b:Interaction.Triggers>
                    <b:EventTrigger EventName="Click">
                    {actions("VSWS_ToggleCommand")}
                    </b:EventTrigger>
                </b:Interaction.Triggers>
            </ls:LSButton>
        </Grid>
        <ControlTemplate.Triggers>
            <Trigger Property="IsMouseOver" Value="True">
                <Setter Property="Opacity" Value="1" TargetName="VisibilityButton"/>
            </Trigger>
            <!-- Another player's character: no button. The comparison is the one the
                 game's own slot triggers make. -->
            <DataTrigger Value="False">
                <DataTrigger.Binding>
                    <MultiBinding Converter="{{StaticResource EqualConverter}}">
                        <Binding RelativeSource="{{RelativeSource AncestorType={{x:Type ls:UIWidget}}}}" Path="DataContext.CurrentPlayer.UserId"/>
                        <Binding Path="DataContext.PlayerCharacterProperties.OwnerUserID" ElementName="EquipmentSlots"/>
                    </MultiBinding>
                </DataTrigger.Binding>
                <Setter Property="Visibility" Value="Collapsed" TargetName="VisibilityButton"/>
            </DataTrigger>
        </ControlTemplate.Triggers>
    </ControlTemplate>"""


# How the game orders a slot among its neighbours: on top while its item list is open.
SLOT_Z = ' Panel.ZIndex="{Binding IsSelecting, Converter={StaticResource BoolToIntConverter}, ConverterParameter=20}"'

# The same for a weapon slot, plus: on top of its neighbours while the mouse is
# over it. A later slot in the row is otherwise drawn over the label that
# opens from an earlier one.
WEAPON_SLOT_STYLE = """    <Style x:Key="VSWS_WeaponSlotStyle" TargetType="Control">
        <Setter Property="Panel.ZIndex" Value="{Binding IsSelecting, Converter={StaticResource BoolToIntConverter}, ConverterParameter=20}"/>
        <Style.Triggers>
            <Trigger Property="IsMouseOver" Value="True">
                <Setter Property="Panel.ZIndex" Value="30"/>
            </Trigger>
        </Style.Triggers>
    </Style>"""


def template(lines, key):
    start = next(i for i, l in enumerate(lines) if f'x:Key="{key}"' in l)
    end = next(i for i in range(start, len(lines)) if "</ControlTemplate>" in lines[i])
    return lines[start:end + 1]


def visibility_button(lines):
    text = "\n".join(template(lines, "VisibilityButtonTemplate"))
    text = text.replace('x:Key="VisibilityButtonTemplate"', 'x:Key="VSWS_VisibilityButtonTemplate"')
    if text.count("{Binding VisibilityType}") != 3:
        sys.exit("the visibility button template no longer has three state triggers")
    text = text.replace("{Binding VisibilityType}", "{Binding Text, ElementName=VSWS_State}")
    for old, new in LABELS.items():
        if old not in text:
            sys.exit(f"label {old} not found in the visibility button template")
        text = text.replace(old, new)
    return label_plate(active_set_state(text))


# Backing for the button and its label: the dark fill and thin edge of the
# game's own option icons (equipmentMenuIconBG in the controller UI).
PLATE_FILL = "#E60A0605"
PLATE_EDGE = "#99413227"
LABEL_GAP = 48   # from the button's edge to the label
LABEL_REACH = 900  # how far the label may extend past the button


def label_plate(text):
    """The game shows the helmet button's label to the right of it, as bare
    text running off into whatever is there. Here the label gets a backing
    plate and opens towards the middle of the panel - to the right of the
    melee slots, to the left of the ranged ones - so it never runs under the
    inventory. The button's square gets the same backing."""
    lines = text.split("\n")

    # The root lays the icon and the label side by side; make it a plain grid
    # so the label can be placed on either side of the icon.
    root = next((i for i, l in enumerate(lines) if l.strip() == '<StackPanel Orientation="Horizontal">'), None)
    close = max((i for i, l in enumerate(lines) if l.strip() == "</StackPanel>"), default=None)
    if root is None or close is None or sum(1 for l in lines if "<StackPanel" in l) != 1:
        sys.exit("the visibility button template is no longer one horizontal StackPanel")
    lines[root] = lines[root].replace('<StackPanel Orientation="Horizontal">', "<Grid>")
    lines[close] = lines[close].replace("</StackPanel>", "</Grid>")

    # Backing under the icon.
    icon = next((i for i, l in enumerate(lines) if 'x:Name="frame"' in l), None)
    if icon is None:
        sys.exit("the visibility button's frame image was not found")
    pad = lines[icon][:len(lines[icon]) - len(lines[icon].lstrip())]
    lines.insert(icon, pad + f'<Rectangle Width="40" Height="40" Fill="{PLATE_FILL}" IsHitTestVisible="False"/>')

    # The label: wrapped in a plate, shown and hidden as a whole.
    label = next((i for i, l in enumerate(lines) if 'Name="HelmetToggleString"' in l), None)
    placement = ' Visibility="Collapsed" Margin="4,0,-600,0"'
    if label is None or placement not in lines[label]:
        sys.exit("the visibility button's label is not where it used to be")
    lines[label] = lines[label].replace(placement, ' VerticalAlignment="Center"')
    label_end = next(i for i in range(label, len(lines)) if "</TextBlock>" in lines[i])
    pad = lines[label][:len(lines[label]) - len(lines[label].lstrip())]
    for i in range(label, label_end + 1):
        lines[i] = "    " + lines[i]
    lines.insert(label_end + 1, pad + "</Border>")
    lines.insert(label, pad + f'<Border x:Name="VSWS_Label" Visibility="Collapsed" IsHitTestVisible="False" '
                 f'HorizontalAlignment="Left" VerticalAlignment="Center" Margin="{LABEL_GAP},0,-{LABEL_REACH},0" '
                 f'Background="{PLATE_FILL}" BorderBrush="{PLATE_EDGE}" BorderThickness="2" CornerRadius="6" Padding="14,4,14,6">')

    hover = '<Setter Property="Visibility" Value="Visible" TargetName="HelmetToggleString"/>'
    if sum(1 for l in lines if hover in l) != 1:
        sys.exit("the trigger that shows the label on hover was not found")
    lines = [l.replace(hover, '<Setter Property="Visibility" Value="Visible" TargetName="VSWS_Label"/>') for l in lines]

    # Ranged slots sit on the right: their label opens to the left.
    out = []
    for l in lines:
        out.append(l)
        if '<DataTrigger Binding="{Binding SlotType}" Value="Ranged' in l:
            pad = l[:len(l) - len(l.lstrip())] + "    "
            out.append(pad + '<Setter Property="HorizontalAlignment" TargetName="VSWS_Label" Value="Right"/>')
            out.append(pad + f'<Setter Property="Margin" TargetName="VSWS_Label" Value="-{LABEL_REACH},0,{LABEL_GAP},0"/>')
    if len(out) != len(lines) + 4:
        sys.exit("expected two ranged-slot triggers to mirror the label in")
    return "\n".join(out)


def active_set_state(text):
    """The game has three visibility states; the mod has a fourth, "shown with
    the current weapon set". It looks like "visible" plus a small weapon-set
    mark, put together from the game's own pictures."""
    lines = text.split("\n")

    # The mark: the icon the controller UI uses for the weapon set - a sword,
    # laid diagonally over the eye with a dark halo so it reads against it.
    # Hidden in the other states. (Sizes were tuned with scripts/mock_icon.py.)
    cover = next((i for i, l in enumerate(lines) if "LS_DisabledPanelColor" in l), None)
    if cover is None:
        sys.exit("the visibility button template has no disabled-cover rectangle to put the mark before")
    pad = lines[cover][:len(lines[cover]) - len(lines[cover].lstrip())]
    lines[cover:cover] = [
        pad + f'<Image x:Name="VSWS_SetMark" Source="{SET_MARK_MELEE}" Width="30" Height="30" '
              'HorizontalAlignment="Center" VerticalAlignment="Center" RenderTransformOrigin="0.5,0.5" '
              'Visibility="Collapsed" IsHitTestVisible="False">',
        pad + '    <Image.RenderTransform>',
        pad + '        <RotateTransform Angle="-45"/>',
        pad + '    </Image.RenderTransform>',
        pad + '    <Image.Effect>',
        pad + '        <DropShadowEffect ShadowDepth="0" BlurRadius="5" Color="Black" Opacity="0.85"/>',
        pad + '    </Image.Effect>',
        pad + '</Image>',
    ]

    # The state: a copy of the "visible" trigger with its own label and the mark shown.
    start = next((i for i, l in enumerate(lines) if "ElementName=VSWS_State}" in l and 'Value="Visible"' in l), None)
    if start is None:
        sys.exit("the trigger for the visible state was not found")
    end = next(i for i in range(start, len(lines)) if "</DataTrigger>" in lines[i])
    block = lines[start:end + 1]
    visible_label = LABELS["h90154bd4g08b9g46efg8e70gbce5d5a99e1a"]
    if not any(visible_label in l for l in block):
        sys.exit("the visible state's label was not found in its trigger")
    block = [l.replace('Value="Visible"', 'Value="ActiveSet"').replace(visible_label, ACTIVE_SET_LABEL) for l in block]
    inner = block[1][:len(block[1]) - len(block[1].lstrip())]
    block.insert(len(block) - 1, inner + '<Setter Property="Visibility" TargetName="VSWS_SetMark" Value="Visible"/>')

    # On the ranged slots the mark is the ranged set's crosshair, upright.
    outer = block[0][:len(block[0]) - len(block[0].lstrip())]
    ranged = []
    for slot in ("RangedMainHand", "RangedOffHand"):
        ranged += [
            "",
            outer + f'<DataTrigger Binding="{{Binding SlotType}}" Value="{slot}">',
            inner + f'<Setter Property="Source" TargetName="VSWS_SetMark" Value="{SET_MARK_RANGED}"/>',
            inner + '<Setter Property="Width" TargetName="VSWS_SetMark" Value="23"/>',
            inner + '<Setter Property="Height" TargetName="VSWS_SetMark" Value="23"/>',
            inner + '<Setter Property="RenderTransform" TargetName="VSWS_SetMark">',
            inner + '    <Setter.Value>',
            inner + '        <RotateTransform Angle="0"/>',
            inner + '    </Setter.Value>',
            inner + '</Setter>',
            outer + '</DataTrigger>',
        ]
    lines[end + 1:end + 1] = [""] + block + ranged
    return "\n".join(lines)


def equipment(lines):
    block = template(lines, "CharacterEquipmentTemplate")
    replaced = 0
    for i, line in enumerate(block):
        for slot in SLOTS:
            if f'x:Name="{slot}"' in line:
                new = line.replace(f'<ls:LSButton x:Name="{slot}"', '<Control Template="{StaticResource VSWS_WeaponEQTemplate}"')
                new = new.replace(' Style="{StaticResource EquipmentSlotStyle}"', "")
                if new == line or "LSButton" in new:
                    sys.exit(f"could not rewrite the line for {slot}")
                # The slot's z-order moves into a style (see WEAPON_SLOT_STYLE):
                # set on the element it could not be raised while the mouse is over it.
                if SLOT_Z not in new:
                    sys.exit(f"the z-order binding of {slot} is not where it used to be")
                new = new.replace(SLOT_Z, ' Style="{StaticResource VSWS_WeaponSlotStyle}"')
                block[i] = new
                replaced += 1
    if replaced != len(SLOTS):
        sys.exit(f"expected {len(SLOTS)} weapon slots, rewrote {replaced}")

    # The armour class badge is declared after the weapon rows and so drawn
    # over them, covering the button labels: lift the two rows above it. And
    # lift the row under the mouse above the other one, whose "Ranged" header
    # would otherwise be drawn over a label coming from the melee side.
    text = "\n".join(block)
    for column in ("0", "2"):
        row = f'<StackPanel Grid.Column="{column}" Grid.Row="1" VerticalAlignment="Bottom">'
        if text.count(row) != 1:
            sys.exit(f"weapon row in column {column} not found exactly once")
        pad = " " * 24
        text = text.replace(row, row + "\n" + "\n".join([
            pad + "<StackPanel.Style>",
            pad + '    <Style TargetType="StackPanel">',
            pad + '        <Setter Property="Panel.ZIndex" Value="1"/>',
            pad + "        <Style.Triggers>",
            pad + '            <Trigger Property="IsMouseOver" Value="True">',
            pad + '                <Setter Property="Panel.ZIndex" Value="5"/>',
            pad + "            </Trigger>",
            pad + "        </Style.Triggers>",
            pad + "    </Style>",
            pad + "</StackPanel.Style>",
        ]))
    return text


def main():
    lines = VANILLA.read_text(encoding="utf-8-sig").splitlines()
    parts = [HEADER, visibility_button(lines), WEAPON_EQ_TEMPLATE, WEAPON_SLOT_STYLE, equipment(lines),
             "</ResourceDictionary>"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n\n".join(parts) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {OUT.read_text(encoding='utf-8').count(chr(10))} lines")


if __name__ == "__main__":
    main()
